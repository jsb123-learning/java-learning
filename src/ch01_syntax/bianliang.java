public class bianliang {
    public static void main(String[] args) {
        /*
        定义8种数据类型的变量:
        整数类型: byte short int long
        浮点类型: float double
        字符类型: char
        布尔类型: boolean

        变量定义的个是:
        数据类型 变量名 = 数据值;
         */

        //定义byte类型的变量
        byte a = 10;
        System.out.println("a的值是:" + a);
        //定义short类型的变量
        short b = 1000;
        System.out.println("b的值是:" + b);
        //定义int类型的变量
        int c = 10000;
        System.out.println("c的值是:" + c);
        //定义long类型的变量
        //long类型的变量后需要加L后缀
        long d = 10000000000000000l;
        System.out.println("d的值是:" + d);
        //定义float类型的变量
        //float类型的变量后需要加f后缀
        float e = 10.0f;
        System.out.println("e的值是:" + e);
        //定义double类型的变量
        double f = 10.0;
        System.out.println("f的值是:" + f);
        //定义char类型的变量
        char g = 'a';
        System.out.println("g的值是:" + g);
        //定义boolean类型的变量
        boolean h = true;
        System.out.println("h的值是:" + h);
    }
}
