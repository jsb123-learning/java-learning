package Lambda_Arrays_综合练习1;

public class girlFriends {
    private String name;
    private int age;
    private double tail;

    public girlFriends() {
    }

    public girlFriends(String name, int age, double tail) {
        this.name = name;
        this.age = age;
        this.tail = tail;
    }

    public String getName() {
        return name;
    }

    public void setName(String name) {
        this.name = name;
    }

    public int getAge() {
        return age;
    }

    public void setAge(int age) {
        this.age = age;
    }

    public double getTail() {
        return tail;
    }

    public void setTail(double tail) {
        this.tail = tail;
    }

    @Override
    public String toString() {
        return super.toString();
    }
}
